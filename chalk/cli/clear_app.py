from typing import Annotated

import typer

from chalk.core import Classroom

from .util import safe

__all__ = ["clear", "add_clear_command"]


def add_clear_command(app: typer.Typer) -> None:
    app.command(no_args_is_help=False)(clear)


@safe
def clear(
    all: Annotated[
        bool,
        typer.Option(
            ...,
            "-a",
            "--all",
            help="Clear every file chalk generates. For now, the same as --autograder.",
        ),
    ] = False,
    autograder: Annotated[
        bool,
        typer.Option(
            ...,
            "--autograder",
            help="Clear only the autograder files (reports and data).",
        ),
    ] = False,
) -> None:
    """
    Clear files generated by chalk. Without options, clears nothing.

    The roster, quizzes, submissions and grades are never removed.
    """
    if all or autograder:
        clear_autograder_files()


def clear_autograder_files() -> None:
    """
    Clear temporary files generated by Chalk, such as reports and data.
    """
    cfg = Classroom.load()
    for quiz in cfg.iter_quizzes():
        for question in quiz.get_questions().values():
            question.clear_autograder_files()
